//! The `h` command: jump to projects (cloning them if needed) and operate the shared object store.
//!
//! The shell function from `h-shell-init` runs `h --root <dir> [--store <dir>] go <term> [clone
//! options] -- <git options>` and `cd`s to the one line printed on stdout; on failure `go` prints
//! the current directory so the shell stays put. Everything else is meant to be run directly,
//! by people and by agents alike.

use std::ffi::{OsStr, OsString};
use std::path::PathBuf;
use std::process::ExitCode;

use h_core::output::{fail, fail_with_cwd, print_cwd, print_path};
use h_core::path::expand_tilde;
use h_git::clone::{CloneRequest, clone_repo, refresh_container_head};
use h_git::git::config_pairs;
use h_git::github;
use h_git::hook;
use h_git::resolve::{
    Casing, Resolution, Target, escape_segment, parse_term, remote_name, resolve,
};
use h_git::store::{FetchReport, Store};

const VERSION: &str = env!("CARGO_PKG_VERSION");

const USAGE: &str = "\
Usage: h [--root DIR] [--store DIR] <command> [args] [-- <git options>]

Commands:
  go <term> [clone options] [--container]
                              print the project directory, cloning it first if needed
  resolve <term>              print the project directory, failing if it is absent
  store init                  create the object store
  store add <term>...         add upstream repositories to the store and fetch them
  store remove <term>...      remove upstreams and their refs from the store (objects stay)
  store fetch [-q] [<term>...]
                              fetch every upstream in the store, or only the named ones
  store list                  list the upstreams in the store
  store path                  print the store directory
  store remote <term>         print the store's name for an upstream, in the store yet or not
  store show <term> <ref>[:<path>]
                              show a commit, or a file at a commit, from the store
  store worktree <term> <ref> [DIR]
                              clone the upstream from the store into DIR (default: a temporary
                              directory) and check <ref> out there
  store maintain [hourly|daily|weekly]
                              run the store's maintenance tasks (default: daily)
  hook worktree-create        Claude Code's WorktreeCreate hook: read its JSON on stdin, add a
                              worktree to the session's clone, and print the worktree's path
  hook worktree-remove        Claude Code's WorktreeRemove hook: commit what is left in the
                              worktree to its branch, then remove the worktree

A term is a project name, <user>/<repo> on GitHub, or a git URL. The code root defaults to
$H_CODE_ROOT, then ~/src; the store to $H_STORE. Git options after `--` (`-c key=value`) are
written into every clone and into the store.";

/// Everything the commands need to know.
struct Config {
    root: PathBuf,
    store: Option<Store>,
    git_opts: Vec<OsString>,
}

fn main() -> ExitCode {
    let mut args: Vec<OsString> = std::env::args_os().skip(1).collect();

    // The shell function passes the identity after `--`, so it never mixes with user arguments.
    let git_opts = match args.iter().rposition(|a| a == "--") {
        Some(i) => {
            let opts = args.split_off(i + 1);
            args.pop();
            opts
        }
        None => Vec::new(),
    };

    // The function generated by earlier versions ran `h --resolve <root> <term> [git options]`.
    if args.first().is_some_and(|a| a == "--resolve") {
        let Some(root) = args.get(1).cloned() else {
            return fail_with_cwd("Usage: h --resolve <code-root> <term>");
        };
        let mut rest: Vec<OsString> = vec!["--root".into(), root, "go".into()];
        rest.extend(args.drain(2..));
        args = rest;
    }

    let mut root = None;
    let mut store = None;
    let mut i = 0;
    while i < args.len() {
        let has_value = i + 1 < args.len();
        match args[i].to_str() {
            Some("--root") if has_value => {
                root = Some(args[i + 1].clone());
                i += 2;
            }
            Some("--store") if has_value => {
                store = Some(args[i + 1].clone());
                i += 2;
            }
            Some("-V" | "--version") => {
                println!("h {VERSION}");
                return ExitCode::SUCCESS;
            }
            Some("-h" | "--help") => {
                println!("h {VERSION}\n{USAGE}");
                return ExitCode::SUCCESS;
            }
            _ if args[i].as_encoded_bytes().starts_with(b"-") => {
                return fail(&format!("Unknown option: {}\n{USAGE}", args[i].to_string_lossy()));
            }
            _ => break,
        }
    }
    let command = args.split_off(i);

    let root =
        root.or_else(|| std::env::var_os("H_CODE_ROOT")).unwrap_or_else(|| OsString::from("~/src"));
    let store = store.or_else(|| std::env::var_os("H_STORE")).filter(|s| !s.is_empty());
    let config = Config {
        root: expand_tilde(&root),
        store: store.map(|s| Store::new(absolute(&s))),
        git_opts,
    };

    let Some((cmd, rest)) = command.split_first() else {
        return fail(&format!("h {VERSION}\n{USAGE}"));
    };
    match cmd.to_str() {
        Some("go") => go(&config, rest),
        Some("resolve") => resolve_cmd(&config, rest),
        Some("store") => store_cmd(&config, rest),
        Some("hook") => hook_cmd(&config, rest),
        _ => fail(&format!("Unknown command: {}\n{USAGE}", cmd.to_string_lossy())),
    }
}

/// `path` with `~` expanded, made absolute: git runs in the store, not the current directory.
fn absolute(path: &OsStr) -> PathBuf {
    let path = expand_tilde(path);
    std::path::absolute(&path).unwrap_or(path)
}

fn utf8(arg: &OsStr) -> Result<&str, String> {
    arg.to_str().ok_or_else(|| format!("Unknown pattern for {}", arg.to_string_lossy()))
}

/// Resolve `term` against the code root, asking GitHub for the canonical casing when `casing`
/// calls for it, with the token git keeps for github.com for this identity.
fn resolve_term(config: &Config, term: &str, casing: Casing) -> Result<Resolution, String> {
    let api = github::api_base();
    resolve(&config.root, term, casing, |user, repo| {
        let token = github::credential_token(&config_pairs(&config.git_opts));
        github::fetch_repo_info(&api, user, repo, token.as_deref())
    })
}

/// `h go <term> [clone options] [--container]`: print the directory, cloning if needed.
fn go(config: &Config, args: &[OsString]) -> ExitCode {
    const USAGE: &str =
        "Usage: h go (<name> | <user>/<repo> | <url>) [clone options] [--container]";
    let Some(term) = args.first() else {
        return fail_with_cwd(USAGE);
    };
    if term == "-h" || term == "--help" {
        return fail_with_cwd(USAGE);
    }
    let term = match utf8(term) {
        Ok(term) => term,
        Err(msg) => return fail_with_cwd(&msg),
    };
    let container = args[1..].iter().any(|a| a == "--container");
    let extra: Vec<OsString> = args[1..].iter().filter(|a| *a != "--container").cloned().collect();

    let resolution = match resolve_term(config, term, Casing::Local) {
        Ok(resolution) => resolution,
        Err(msg) => return fail_with_cwd(&msg),
    };
    if resolution.path.is_dir() {
        refresh_container_head(&resolution.path);
        print_path(&resolution.path);
        return ExitCode::SUCCESS;
    }
    let Some(url) = &resolution.clone_url else {
        return fail_with_cwd(&format!("{term} not found"));
    };

    let store = config.store.as_ref().filter(|s| s.exists());
    let reference_names = store.map(|s| shared_upstreams(s, &resolution)).unwrap_or_default();
    let request = CloneRequest {
        url,
        path: &resolution.path,
        git_opts: &config.git_opts,
        extra: &extra,
        reference: store.map(|s| s.path.as_path()),
        reference_names: &reference_names,
        container,
        upstream_url: resolution.upstream_url.as_deref(),
    };
    match clone_repo(&request) {
        0 => {
            print_path(&resolution.path);
            ExitCode::SUCCESS
        }
        code => {
            print_cwd();
            ExitCode::from(code)
        }
    }
}

/// The store's names for the upstreams a clone of `resolution` shares history with: its own and,
/// for a fork, its parent's. Each is spelled as the store spells it when the store has it
/// (GitHub names ignore case), and as it would be added otherwise.
fn shared_upstreams(store: &Store, resolution: &Resolution) -> Vec<String> {
    let existing = store.remotes().unwrap_or_default();
    let parent = resolution.upstream_url.as_deref().and_then(|url| match parse_term(url) {
        Ok(Target::GitHub { user, repo }) => {
            Some(remote_name("github.com", &format!("{user}/{repo}")))
        }
        _ => None,
    });
    let in_store = |name: String| {
        let exact = existing.iter().find(|r| **r == name);
        let found = exact.or_else(|| existing.iter().find(|r| r.eq_ignore_ascii_case(&name)));
        found.cloned().unwrap_or(name)
    };
    resolution.remote.clone().into_iter().chain(parent).map(in_store).collect()
}

/// `h resolve <term>`: print the directory, or fail when it does not exist.
fn resolve_cmd(config: &Config, args: &[OsString]) -> ExitCode {
    let Some(term) = args.first() else {
        return fail("Usage: h resolve (<name> | <user>/<repo> | <url>)");
    };
    let term = match utf8(term) {
        Ok(term) => term,
        Err(msg) => return fail(&msg),
    };
    // Only existing checkouts are printed, and those are found in any casing without GitHub.
    match resolve(&config.root, term, Casing::Local, |_, _| None) {
        Ok(resolution) if resolution.path.is_dir() => {
            print_path(&resolution.path);
            ExitCode::SUCCESS
        }
        Ok(_) => fail(&format!("{term} not found")),
        Err(msg) => fail(&msg),
    }
}

/// An upstream: its remote name and, when it is not in the store yet, the URL to add it from.
struct Upstream {
    name: String,
    url: Option<String>,
}

/// The store's name for `term`, preferring an upstream already in the store over a GitHub
/// lookup, and finding a bare project name among the upstreams' last path segments. A name as
/// `h store list` prints it is taken as it is.
fn upstream_for(config: &Config, store: &Store, term: &str) -> Result<Upstream, String> {
    let existing = match store.exists() {
        true => store.remotes().map_err(|e| e.to_string())?,
        false => Vec::new(),
    };
    if existing.iter().any(|r| r == term) {
        return Ok(Upstream { name: term.to_string(), url: None });
    }
    let target = parse_term(term).map_err(|_| format!("Unknown pattern for {term}"))?;
    let candidate = match &target {
        Target::GitHub { user, repo } => Some(remote_name("github.com", &format!("{user}/{repo}"))),
        Target::Remote { .. } | Target::Name(_) => None,
    };
    if let Some(candidate) = candidate
        && let Some(name) = existing.iter().find(|r| r.eq_ignore_ascii_case(&candidate))
    {
        return Ok(Upstream { name: name.clone(), url: None });
    }
    if let Target::Name(name) = &target {
        let name = &escape_segment(name);
        let case_sensitive = name.bytes().any(|b| b.is_ascii_uppercase());
        let matches: Vec<&String> = existing
            .iter()
            .filter(|r| {
                let last = r.rsplit('/').next().unwrap_or(r);
                if case_sensitive { last == name } else { last.eq_ignore_ascii_case(name) }
            })
            .collect();
        return match matches.as_slice() {
            [one] => Ok(Upstream { name: (*one).clone(), url: None }),
            [] => Err(format!("{term} is not in the store")),
            many => {
                let names: Vec<&str> = many.iter().map(|s| s.as_str()).collect();
                Err(format!("{term} is ambiguous in the store: {}", names.join(", ")))
            }
        };
    }
    let resolution = resolve_term(config, term, Casing::GitHub)?;
    match (resolution.remote, resolution.clone_url) {
        (Some(name), _) if existing.contains(&name) => Ok(Upstream { name, url: None }),
        (Some(name), url @ Some(_)) => Ok(Upstream { name, url }),
        _ => Err(format!("{term} cannot be added to the store")),
    }
}

/// The name of the upstream `term` names, which must be in the store.
fn upstream_in_store(config: &Config, store: &Store, term: &str) -> Result<String, String> {
    match upstream_for(config, store, term)? {
        Upstream { name, url: None } => Ok(name),
        Upstream { url: Some(_), .. } => Err(format!("{term} is not in the store")),
    }
}

/// `h store <subcommand> ...`
fn store_cmd(config: &Config, args: &[OsString]) -> ExitCode {
    let Some(store) = &config.store else {
        return fail("No store configured: pass --store DIR or set H_STORE");
    };
    let Some((sub, rest)) = args.split_first() else {
        return fail(USAGE);
    };
    let terms: Result<Vec<&str>, String> = rest.iter().map(|a| utf8(a)).collect();
    let terms = match terms {
        Ok(terms) => terms,
        Err(msg) => return fail(&msg),
    };
    let result = match sub.to_str() {
        Some("init") => store
            .init(&config.git_opts)
            .map(|()| print_path(&store.path))
            .map_err(|e| e.to_string()),
        Some("path") => {
            print_path(&store.path);
            Ok(())
        }
        Some("list") => store_list(store),
        Some("add") => store_add(config, store, &terms),
        Some("remove") => store_remove(config, store, &terms),
        Some("fetch") => store_fetch(config, store, &terms),
        Some("remote") => match terms.as_slice() {
            [term] => upstream_for(config, store, term).map(|u| println!("{}", u.name)),
            _ => Err("Usage: h store remote <term>".into()),
        },
        Some("show") => match terms.as_slice() {
            [term, spec] => upstream_in_store(config, store, term)
                .and_then(|name| store.show(&name, spec).map_err(|e| e.to_string())),
            _ => Err("Usage: h store show <term> <ref>[:<path>]".into()),
        },
        Some("worktree") => match terms.as_slice() {
            [term, reference] | [term, reference, _] => {
                let dir = rest.get(2).map(|d| absolute(d));
                upstream_in_store(config, store, term).and_then(|name| {
                    store
                        .worktree(&name, reference, dir, &config.git_opts)
                        .map(|dir| print_path(&dir))
                        .map_err(|e| e.to_string())
                })
            }
            _ => Err("Usage: h store worktree <term> <ref> [DIR]".into()),
        },
        Some("maintain") => match terms.as_slice() {
            [] => store.maintain("daily").map_err(|e| e.to_string()),
            [schedule] => store.maintain(schedule).map_err(|e| e.to_string()),
            _ => Err("Usage: h store maintain [hourly|daily|weekly]".into()),
        },
        _ => Err(format!("Unknown store command: {}\n{USAGE}", sub.to_string_lossy())),
    };
    match result {
        Ok(()) => ExitCode::SUCCESS,
        Err(msg) => fail(&msg),
    }
}

fn store_list(store: &Store) -> Result<(), String> {
    for name in store.remotes().map_err(|e| e.to_string())? {
        println!("{name}");
    }
    Ok(())
}

fn store_add(config: &Config, store: &Store, terms: &[&str]) -> Result<(), String> {
    if terms.is_empty() {
        return Err("Usage: h store add <term>...".into());
    }
    // Every term is checked before anything changes.
    let mut upstreams: Vec<Upstream> = Vec::new();
    for term in terms {
        let upstream = upstream_for(config, store, term)?;
        if !upstreams.iter().any(|u| u.name == upstream.name) {
            upstreams.push(upstream);
        }
    }
    if !store.exists() {
        store.init(&config.git_opts).map_err(|e| e.to_string())?;
    }
    let mut added = Vec::new();
    for Upstream { name, url } in &upstreams {
        let Some(url) = url else {
            eprintln!("{name} is already in the store");
            continue;
        };
        match store.add_remote(name, url) {
            Ok(true) => {
                eprintln!("added {name}");
                added.push(name.clone());
            }
            Ok(false) => eprintln!("{name} is already in the store"),
            Err(e) => {
                remove_again(store, &added, "since adding the rest failed");
                return Err(e.to_string());
            }
        }
    }
    let names: Vec<String> = upstreams.into_iter().map(|u| u.name).collect();
    let mut report = store.fetch(&names, false).map_err(|e| e.to_string())?;
    // An upstream that has nothing after a failed fetch was the one, or one of those, that
    // failed: it goes again, so the store never holds an upstream that was never fetched.
    if report.failed.is_some() {
        let unfetched: Vec<String> =
            added.into_iter().filter(|name| !store.has_refs(name).unwrap_or(true)).collect();
        remove_again(store, &unfetched, "since it could not be fetched");
        report.headless.retain(|name| !unfetched.contains(name));
        report.heads_failed.retain(|(name, _)| !unfetched.contains(name));
    }
    for name in &report.headless {
        eprintln!("{name} has no default branch, so {name}/-/HEAD is not set");
    }
    fetch_result(report)
}

/// Take the upstreams `store add` just added out of the store again, saying so and `why`.
fn remove_again(store: &Store, names: &[String], why: &str) {
    for name in names {
        match store.remove_remote(name) {
            Ok(()) => eprintln!("removed {name} again, {why}"),
            Err(e) => eprintln!("could not remove {name} again: {e}"),
        }
    }
}

fn store_remove(config: &Config, store: &Store, terms: &[&str]) -> Result<(), String> {
    if terms.is_empty() {
        return Err("Usage: h store remove <term>...".into());
    }
    if !store.exists() {
        return Err(format!("No store at {}", store.path.display()));
    }
    let mut names = Vec::new();
    for term in terms {
        let name = upstream_in_store(config, store, term)?;
        if !names.contains(&name) {
            names.push(name);
        }
    }
    for name in names {
        store.remove_remote(&name).map_err(|e| e.to_string())?;
        eprintln!("removed {name}");
    }
    Ok(())
}

fn store_fetch(config: &Config, store: &Store, terms: &[&str]) -> Result<(), String> {
    if !store.exists() {
        return Err(format!("No store at {}: run `h store init` first", store.path.display()));
    }
    let quiet = terms.iter().any(|t| *t == "-q" || *t == "--quiet");
    let mut names = Vec::new();
    for term in terms.iter().filter(|t| **t != "-q" && **t != "--quiet") {
        names.push(upstream_in_store(config, store, term)?);
    }
    let report = store.fetch(&names, quiet).map_err(|e| e.to_string())?;
    for name in report.headless.iter().filter(|_| !quiet) {
        eprintln!("{name} has no default branch, so {name}/-/HEAD is not updated");
    }
    fetch_result(report)
}

/// Fail when a fetch did not do everything, after naming the upstreams whose HEAD it could not
/// update. Git has already named the upstreams it could not fetch.
fn fetch_result(report: FetchReport) -> Result<(), String> {
    for (name, err) in &report.heads_failed {
        eprintln!("could not update {name}/-/HEAD: {err}");
    }
    match report.failed {
        Some(err) => Err(err.to_string()),
        None if report.heads_failed.is_empty() => Ok(()),
        None => Err("some upstreams' HEADs could not be updated".into()),
    }
}

/// `h hook <event>`: a Claude Code hook, reading the hook's JSON input on stdin. Failures exit
/// with 1, never 2, which Claude Code reads as a missing hook script.
fn hook_cmd(config: &Config, args: &[OsString]) -> ExitCode {
    const USAGE: &str = "Usage: h hook (worktree-create | worktree-remove) < hook-input.json";
    let event = match args {
        [event] => event.to_str(),
        _ => None,
    };
    let Some(event @ ("worktree-create" | "worktree-remove")) = event else {
        return fail(USAGE);
    };
    let mut input = String::new();
    if let Err(err) = std::io::Read::read_to_string(&mut std::io::stdin(), &mut input) {
        return fail(&format!("h hook {event}: cannot read the hook input: {err}"));
    }
    let result = if event == "worktree-create" {
        hook::create(&input, config.store.as_ref()).map(|created| {
            let path = created.path.display();
            eprintln!("{path}: on {}, from {}", created.branch, created.base);
            print_path(&created.path);
        })
    } else {
        hook::remove(&input).map(|removed| match removed {
            hook::Removed::Missing => eprintln!("nothing to remove"),
            hook::Removed::Removed { branch, saved } => {
                let kept = match (branch, saved) {
                    (Some(branch), true) => format!("; its uncommitted work is on {branch}"),
                    (Some(branch), false) => format!("; its work is on {branch}"),
                    (None, _) => String::new(),
                };
                eprintln!("removed the worktree{kept}");
            }
        })
    };
    match result {
        Ok(()) => ExitCode::SUCCESS,
        Err(err) => fail(&format!("h hook {event}: {err}")),
    }
}
