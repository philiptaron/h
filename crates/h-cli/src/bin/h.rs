//! The `h` command: jump to projects, cloning them if needed.
//!
//! The shell function from `h-shell-init` runs `h --root <dir> go <term> [clone options] -- <git
//! options>` and `cd`s to the one line printed on stdout; on failure `go` prints the current
//! directory so the shell stays put. Everything else is meant to be run directly, by people and
//! by agents alike.

use std::ffi::{OsStr, OsString};
use std::path::PathBuf;
use std::process::ExitCode;

use h_core::output::{fail, fail_with_cwd, print_cwd, print_path};
use h_core::path::expand_tilde;
use h_git::clone::{CloneRequest, clone_repo};
use h_git::github;
use h_git::resolve::{Resolution, resolve};

const VERSION: &str = env!("CARGO_PKG_VERSION");

const USAGE: &str = "\
Usage: h [--root DIR] <command> [args] [-- <git options>]

Commands:
  go <term> [clone options]   print the project directory, cloning it first if needed
  resolve <term>              print the project directory, failing if it is absent

A term is a project name, <user>/<repo> on GitHub, or a git URL. The code root defaults to
$H_CODE_ROOT, then ~/src. Git options after `--` (`-c key=value`) are written into every
clone.";

/// Everything the commands need to know.
struct Config {
    root: PathBuf,
    git_opts: Vec<OsString>,
}

fn main() -> ExitCode {
    let mut args: Vec<OsString> = std::env::args_os().skip(1).collect();

    // The shell function passes the identity after `--`, so it never mixes with user arguments.
    let git_opts = match args.iter().rposition(|a| a == "--") {
        Some(i) => {
            let opts = args.split_off(i + 1);
            args.pop();
            opts
        }
        None => Vec::new(),
    };

    // The function generated by earlier versions ran `h --resolve <root> <term> [git options]`.
    if args.first().is_some_and(|a| a == "--resolve") {
        let Some(root) = args.get(1).cloned() else {
            return fail_with_cwd("Usage: h --resolve <code-root> <term>");
        };
        let mut rest: Vec<OsString> = vec!["--root".into(), root, "go".into()];
        rest.extend(args.drain(2..));
        args = rest;
    }

    let mut root = None;
    let mut i = 0;
    while i < args.len() {
        let has_value = i + 1 < args.len();
        match args[i].to_str() {
            Some("--root") if has_value => {
                root = Some(args[i + 1].clone());
                i += 2;
            }
            Some("-V" | "--version") => {
                println!("h {VERSION}");
                return ExitCode::SUCCESS;
            }
            Some("-h" | "--help") => {
                println!("h {VERSION}\n{USAGE}");
                return ExitCode::SUCCESS;
            }
            _ if args[i].as_encoded_bytes().starts_with(b"-") => {
                return fail(&format!("Unknown option: {}\n{USAGE}", args[i].to_string_lossy()));
            }
            _ => break,
        }
    }
    let command = args.split_off(i);

    let root =
        root.or_else(|| std::env::var_os("H_CODE_ROOT")).unwrap_or_else(|| OsString::from("~/src"));
    let config = Config { root: expand_tilde(&root), git_opts };

    let Some((cmd, rest)) = command.split_first() else {
        return fail(&format!("h {VERSION}\n{USAGE}"));
    };
    match cmd.to_str() {
        Some("go") => go(&config, rest),
        Some("resolve") => resolve_cmd(&config, rest),
        _ => fail(&format!("Unknown command: {}\n{USAGE}", cmd.to_string_lossy())),
    }
}

fn utf8(arg: &OsStr) -> Result<&str, String> {
    arg.to_str().ok_or_else(|| format!("Unknown pattern for {}", arg.to_string_lossy()))
}

/// Resolve `term` against the code root, asking GitHub for the canonical casing.
fn resolve_term(config: &Config, term: &str) -> Result<Resolution, String> {
    let api = github::api_base();
    resolve(&config.root, term, |user, repo| github::fetch_repo_info(&api, user, repo))
}

/// `h go <term> [clone options]`: print the directory, cloning if needed.
fn go(config: &Config, args: &[OsString]) -> ExitCode {
    const USAGE: &str = "Usage: h go (<name> | <user>/<repo> | <url>) [clone options]";
    let Some(term) = args.first() else {
        return fail_with_cwd(USAGE);
    };
    if term == "-h" || term == "--help" {
        return fail_with_cwd(USAGE);
    }
    let term = match utf8(term) {
        Ok(term) => term,
        Err(msg) => return fail_with_cwd(&msg),
    };

    let resolution = match resolve_term(config, term) {
        Ok(resolution) => resolution,
        Err(msg) => return fail_with_cwd(&msg),
    };
    if resolution.path.is_dir() {
        print_path(&resolution.path);
        return ExitCode::SUCCESS;
    }
    let Some(url) = &resolution.clone_url else {
        return fail_with_cwd(&format!("{term} not found"));
    };

    let request = CloneRequest {
        url,
        path: &resolution.path,
        git_opts: &config.git_opts,
        extra: &args[1..],
        upstream_url: resolution.upstream_url.as_deref(),
    };
    match clone_repo(&request) {
        0 => {
            print_path(&resolution.path);
            ExitCode::SUCCESS
        }
        code => {
            print_cwd();
            ExitCode::from(code)
        }
    }
}

/// `h resolve <term>`: print the directory, or fail when it does not exist.
fn resolve_cmd(config: &Config, args: &[OsString]) -> ExitCode {
    let Some(term) = args.first() else {
        return fail("Usage: h resolve (<name> | <user>/<repo> | <url>)");
    };
    let term = match utf8(term) {
        Ok(term) => term,
        Err(msg) => return fail(&msg),
    };
    match resolve_term(config, term) {
        Ok(resolution) if resolution.path.is_dir() => {
            print_path(&resolution.path);
            ExitCode::SUCCESS
        }
        Ok(_) => fail(&format!("{term} not found")),
        Err(msg) => fail(&msg),
    }
}
